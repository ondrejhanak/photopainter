#!/usr/bin/env python3
"""Generate a C font table (lib/Fonts/fontNN.c) from a BDF bitmap font.

Covers U+0020..U+017F (ASCII, Latin-1 Supplement, Latin Extended-A), so any Latin-script language
needs only strings. Characters the font lacks (the U+007F..U+009F control codes) get its '?' glyph.
Output matches GUI_Paint's format: one row after another, each row ceil(width / 8) bytes, MSB is
the leftmost pixel.

    python3 tools/gen_font.py ter-u22b.bdf Font22 > lib/Fonts/font22.c
"""

import argparse
import sys
import unicodedata

FIRST, LAST = 0x20, 0x17F


def load_bdf(path):
    """Return (width, height, {code point: [row bits, top to bottom, width bits each]})."""
    width = height = descent = None
    glyphs = {}
    with open(path, encoding="ascii", errors="replace") as f:
        lines = iter(f.read().splitlines())
    for line in lines:
        key, _, rest = line.partition(" ")
        if key == "FONTBOUNDINGBOX":
            width, height, _, yoff = map(int, rest.split())
            descent = -yoff
        elif key == "ENCODING":
            cp = int(rest.split()[0])
        elif key == "BBX":
            gw, gh, gx, gy = map(int, rest.split())
        elif key == "BITMAP":
            rows = [0] * height
            top = height - descent - (gy + gh) # glyph box position inside the font cell
            nbits = (gw + 7) // 8 * 8
            for i in range(gh):
                bits = int(next(lines), 16) >> (nbits - gw) # glyph row, gw bits
                y = top + i
                if 0 <= y < height:
                    shift = width - gx - gw
                    rows[y] = bits << shift if shift >= 0 else bits >> -shift
            glyphs[cp] = rows
    if width is None:
        sys.exit(f"{path}: no FONTBOUNDINGBOX")
    return width, height, glyphs


def char_name(cp):
    return unicodedata.name(chr(cp), "control")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("bdf", help="BDF font file, e.g. ter-u22b.bdf")
    ap.add_argument("name", help="C name of the sFONT, e.g. Font22")
    ap.add_argument("--source", default="", help="source description for the header comment")
    args = ap.parse_args()

    width, height, glyphs = load_bdf(args.bdf)
    nbytes = (width + 7) // 8
    source = args.source or args.bdf.rsplit("/", 1)[-1]

    out = [
        f"// {args.name}: {width}x{height} px, U+{FIRST:04X}..U+{LAST:04X}, generated by tools/gen_font.py",
        f"// from {source}. Do not edit by hand.",
        "// Font data: SIL Open Font License 1.1, see OFL.TXT in this folder.",
        "",
        '#include "fonts.h"',
        "",
        f"const uint8_t {args.name}_Table[] = {{",
    ]
    for cp in range(FIRST, LAST + 1):
        rows = glyphs.get(cp, glyphs[ord("?")])
        label = chr(cp) if cp in glyphs else "? (missing)"
        out.append(f"\t// U+{cp:04X} {label} {char_name(cp)}")
        for bits in rows:
            data = ", ".join(f"0x{(bits << (nbytes * 8 - width)) >> (8 * (nbytes - 1 - i)) & 0xFF:02X}"
                             for i in range(nbytes))
            art = "".join("#" if bits >> (width - 1 - x) & 1 else " " for x in range(width))
            out.append(f"\t{data}, //" + (f" {art.rstrip()}" if art.strip() else ""))
    out += [
        "};",
        "",
        f"sFONT {args.name} = {{",
        f"  {args.name}_Table,",
        f"  {width}, /* Width */",
        f"  {height}, /* Height */",
        f"  0x{LAST:X}, /* Last */",
        "};",
        "",
    ]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
